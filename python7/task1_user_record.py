# Исходная необработанная строка из источника данных.
# Формат: UID ; имя ; город ; статус
raw_user_record = " 10827 ; aLeXanDer_vLaDiMiRoV ; miNsk ; ACTIVE "

# Разбиваем исходную строку на отдельные элементы
# с помощью разделителя ";".
parts = raw_user_record.split(";")

# Очищаем каждый элемент от лишних пробелов
# и других пробельных символов по краям строки.
uid = parts[0].strip()
name = parts[1].strip()
city = parts[2].strip()
status = parts[3].strip()

# Добавляем к идентификатору пользователя префикс UID-
# с помощью форматирования строки.
uid = f"UID-{uid}"

# Заменяем символы подчеркивания в имени на пробелы.
# Затем приводим каждое слово к виду с заглавной первой буквой.
name = name.replace("_", " ").title()

# Приводим название города к верхнему регистру.
city = city.upper()

# Приводим статус пользователя к нижнему регистру.
status = status.lower()

# Объединяем все обработанные элементы в одну строку
# с разделителем "|".
normalized_record = " | ".join([uid, name, city, status])

# Выводим нормализованную запись на экран.
print(f"Нормализованная запись: {normalized_record}")